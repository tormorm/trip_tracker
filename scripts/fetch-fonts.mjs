// One-off: download the Google Fonts subsets we need into public/fonts and
// write src/styles/fonts.css pointing at the local copies (fonts must work offline).
// Re-run only if you change families/weights: `node scripts/fetch-fonts.mjs`
import fs from 'node:fs';
import path from 'node:path';

const CSS_URL =
  'https://fonts.googleapis.com/css2?family=Be+Vietnam+Pro:wght@400;500;600;700;800' +
  '&family=Fraunces:ital,opsz,wght@0,9..144,700;1,9..144,500' +
  '&family=Noto+Sans+Khmer:wght@400;700&display=swap';
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/124.0 Safari/537.36';
// Subsets worth shipping. Khmer font only needs the Khmer block (Latin comes from Be Vietnam Pro).
const KEEP = { 'Be Vietnam Pro': ['vietnamese', 'latin-ext', 'latin'], Fraunces: ['vietnamese', 'latin-ext', 'latin'], 'Noto Sans Khmer': ['khmer'] };

const css = await (await fetch(CSS_URL, { headers: { 'User-Agent': UA } })).text();
const outDir = 'public/fonts';
fs.mkdirSync(outDir, { recursive: true });
const blocks = [...css.matchAll(/\/\* ([\w-]+) \*\/\s*(@font-face \{[^}]+\})/g)];
const seen = new Map();
let out = '/* Generated by scripts/fetch-fonts.mjs — SIL Open Font License 1.1 (see public/fonts/OFL.txt) */\n';
for (const [, subset, block] of blocks) {
  const family = block.match(/font-family: '([^']+)'/)[1];
  if (!KEEP[family]?.includes(subset)) continue;
  const url = block.match(/url\((https:[^)]+)\)/)[1];
  if (!seen.has(url)) {
    const style = block.match(/font-style: (\w+)/)[1];
    const name = `${family.replace(/ /g, '')}-${style}-${subset}-${seen.size}.woff2`.toLowerCase();
    const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
    fs.writeFileSync(path.join(outDir, name), buf);
    seen.set(url, name);
    console.log(name, buf.length);
  }
  out += `/* ${subset} */\n` + block.replace(url, `/fonts/${seen.get(url)}`) + '\n';
}
fs.writeFileSync('src/styles/fonts.css', out);
